const {assert,sql,load,root,send,data,product,imported,line}=require('./isolated-harness.cjs'),path=require('node:path');
const {stockCostBasis,manualStockCost}=load(path.join(root,'lib/manual-stock-cost.ts'));
const {reportFinancialTotals}=load(path.join(root,'lib/product-report.ts'));
const {buildFreightAnalysis}=load(path.join(root,'lib/freight-reconciliation.ts'));
(async()=>{
 const at=Date.now()-60000;await product('COST','手工成本商品',{stock_mode:'direct',quantity:100,count_at:at,cost:2});
 const a={...line('COST-ORDER','COST',2,'已发货',at+1000),shipped_at:at+2000};await imported([a]);
 const current=()=>sql.prepare('select * from orders where key=?').get(a.key);
 const before=sql.prepare('select quantity from products where code=?').get('COST').quantity;
 const b={action:'manual_stock_cost',request_id:'cost-save',key:a.key,basis:stockCostBasis(current()),cost_at:0,cost:'6.25',note:'2份货品合计成本'};
 await send(b);await send(b);
 assert.equal(manualStockCost(current()),6.25);assert.equal(sql.prepare('select count(*) n from stock_cost_events').get().n,1);
 assert.equal(sql.prepare('select quantity from products where code=?').get('COST').quantity,before);
 assert.equal(current().unit_cost_snapshot,2);assert.equal(current().deducted_qty,2);
 const refreshed=(await data()).orders.find(o=>o.key===a.key);assert.equal(refreshed.manual_stock_cost_cents,625);
 assert.equal(reportFinancialTotals([], [refreshed]).gross,3.75);
 const freight={freightBills:[],freightPeriods:[],packingSettings:{fee_cents:0}};
 assert.equal(buildFreightAnalysis([refreshed],freight).rows[0].goods,625);
 await imported([a]);assert.equal(manualStockCost(current()),6.25,'ERP keeps manual cost');
 await send({...b,request_id:'stale',cost:'7'},400);
 await send({...b,request_id:'invalid',cost_at:current().manual_stock_cost_at,cost:'-2'},400);
 await send({...b,request_id:'precision',cost_at:current().manual_stock_cost_at,cost:'1.234'},400);
 await send({...b,request_id:'zero',cost_at:current().manual_stock_cost_at,cost:'0'},400);
 await send({...b,request_id:'edit',cost_at:current().manual_stock_cost_at,cost:'7',note:'更正成本'});
 assert.equal(manualStockCost(current()),7);assert.equal(sql.prepare('select previous_cents from stock_cost_events where id=?').get('edit').previous_cents,625);
 sql.prepare('update orders set quantity=3 where key=?').run(a.key);
 assert.equal(manualStockCost(current()),null);assert.equal(reportFinancialTotals([], [current()]).gross,null);
 assert.equal(buildFreightAnalysis([current()],freight).rows[0].goods,null);
 assert.equal(manualStockCost({...current(),manual_stock_cost_cents:null}),undefined);
 assert.equal(reportFinancialTotals([],[{...current(),fulfillment_mode:'print',printing_allocated_cost:3}]).gross,7,'print takes precedence, never double charges');
 sql.prepare("insert into digit_fulfillments(scope,order_key,status,color,reason,signature,updated_at) values('isolated',?,'print','','','',?)").run(a.key,at);
 await send({...b,request_id:'print-block',basis:stockCostBasis(current()),cost_at:current().manual_stock_cost_at},400);
 console.log('PASS manual cost persistence, audit, idempotency, stock unchanged, precision, optimistic lock, stale-cost exclusion and print precedence');
})().catch(e=>{console.error(e);process.exitCode=1});
