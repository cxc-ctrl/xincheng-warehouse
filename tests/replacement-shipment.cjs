const {assert,sql,send,product,imported,line,qty,load,root,data}=require('./isolated-harness.cjs');
const {orderFingerprint}=load(root+'/lib/order-policy.ts');
const {returnPlan}=load(root+'/lib/return-plan.ts');
(async()=>{
 const at=Date.now()-60000;
 sql.prepare("INSERT INTO shop_configs VALUES ('isolated','shop-id','test','isolated','测试店','现货团队','own',1,?)").run(at);
 await product('A','原款');
 await product('B','换货款',{stock_mode:'direct',cost:3});
 sql.prepare("UPDATE products SET quantity=50,count_at=? WHERE code='B'").run(at);
 await send({action:'physical_product',new_product:true,product:{code:'STOCK-A',name:'原款库存',unit:'张',cost:1}});
 sql.prepare("UPDATE physical_stocks SET quantity=50,count_at=? WHERE code='STOCK-A'").run(at);
 await send({action:'stock_rule',sales_codes:['A'],items:[{stock_code:'STOCK-A',per_unit:2}],at});
 const source=(id,remarks='')=>({...line(id,'A',2,'已发货',at+1000),shipped_at:at+2000,seller_remark:remarks});
 const command=(id,actual)=>({action:'manual_outbound',at:at+3000,note:'客户确认实际发货款式',order:{shop:'isolated',platform:'test',orderId:id,sku:'A',quantity:2,actual}});
 const bCount=()=>sql.prepare("SELECT quantity FROM products WHERE code='B'").get().quantity;
 const saved=o=>sql.prepare('SELECT * FROM orders WHERE key=?').get(o.key);
 const first=source('FIRST');
 await send(command('FIRST',[{sku:'B',quantity:2}]));
 await imported([first]);await imported([first]);
 assert.equal(qty('STOCK-A'),50);assert.equal(bCount(),48);
 assert.equal(saved(first).code,'A');
 assert.equal(saved(first).unit_cost_snapshot,3);
 const late=source('LATE');
 await imported([late]);assert.equal(qty('STOCK-A'),46);
 await send(command('LATE',[{sku:'A',quantity:1},{sku:'B',quantity:1}]));
 await imported([late]);assert.equal(qty('STOCK-A'),48);assert.equal(bCount(),47);
 assert.equal(sql.prepare("SELECT count(*) n FROM order_conflicts WHERE order_key=?").get(late.key).n,0);
 const warehouse=await data(),updated=warehouse.orders.find(o=>o.key===late.key);
 assert.deepEqual(returnPlan(updated,warehouse.products,warehouse.physical,warehouse.rules,warehouse.returns).map(x=>[x.code,x.max]).sort(),[['B',1],['STOCK-A',2]]);
 await send({action:'order_review',mode:'return',key:late.key,fingerprint:orderFingerprint(saved(late)),items:[{kind:'product',code:'B',quantity:1}],note:'收到B款',at:at+5000});
 assert.equal(bCount(),48);assert.equal(qty('STOCK-A'),48);
 const held=source('HELD','客户改发 B 款');
 await imported([held]);assert.equal(saved(held).shipped_qty,0);assert.equal(saved(held).review,1);assert.equal(qty('STOCK-A'),48);
 await send(command('HELD',[{sku:'B',quantity:1}]),400);assert.equal(bCount(),48);
 await send(command('HELD',[{sku:'B',quantity:2}]));
 await imported([held]);assert.equal(saved(held).shipped_qty,2);assert.equal(saved(held).review,0);assert.equal(qty('STOCK-A'),48);assert.equal(bCount(),46);
 await send(command('HELD',[{sku:'B',quantity:2}]),400);
 assert.equal(bCount(),46);
 console.log('PASS replacement shipment before and after import, mixed allocations, review hold, actual item returns, cost and duplicate protection');
})().catch(error=>{console.error(error);process.exitCode=1;});
